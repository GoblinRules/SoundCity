param()
# Regenerate the editable vector artwork, WPF drawings, PNGs and multi-resolution ICO.
# Uses Windows' vector renderer; no downloaded artwork or graphics packages are needed.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore, PresentationFramework, WindowsBase
$taskRoot = Split-Path -Parent $PSScriptRoot
$assetDir = Join-Path $taskRoot 'assets'
$appAssetDir = Join-Path $taskRoot 'src\SoundCity.App\Assets'
[void][IO.Directory]::CreateDirectory($assetDir)
[void][IO.Directory]::CreateDirectory($appAssetDir)
$utf8 = New-Object Text.UTF8Encoding($false)
$culture = [Globalization.CultureInfo]::InvariantCulture

# The open C encloses three skyline / audio bars. A shared 512-unit drawing keeps
# the SVG, native WPF branding and Windows icons in sync.
$arc = 'M 358,154 A 144,144 0 1 0 358,358'
$bars = @(@(202,232,30,48), @(258,184,30,144), @(314,212,30,88))
$svgDefs = @'
<defs>
 <linearGradient id="tile" x2="0.85" y2="1"><stop stop-color="#222C3B"/><stop offset="1" stop-color="#0A0E15"/></linearGradient>
 <linearGradient id="orange" x1="0" y1="0" x2="0.65" y2="1"><stop stop-color="#FFC17B"/><stop offset="0.48" stop-color="#FF984C"/><stop offset="1" stop-color="#FF7133"/></linearGradient>
</defs>
'@
$svgMark = "<path d=`"$arc`" fill=`"none`" stroke=`"url(#orange)`" stroke-width=`"34`" stroke-linecap=`"round`"/>"
foreach ($b in $bars) { $svgMark += "<rect x=`"$($b[0])`" y=`"$($b[1])`" width=`"$($b[2])`" height=`"$($b[3])`" rx=`"15`" fill=`"url(#orange)`"/>" }
$svgTile = '<rect x="8" y="8" width="496" height="496" rx="112" fill="url(#tile)" stroke="#354050" stroke-width="4"/>'
$svgIcon = "<svg xmlns=`"http://www.w3.org/2000/svg`" viewBox=`"0 0 512 512`" role=`"img`" aria-label=`"SoundCity`">$svgDefs$svgTile$svgMark</svg>"
[IO.File]::WriteAllText((Join-Path $assetDir 'icon.svg'), $svgIcon, $utf8)
[IO.File]::WriteAllText((Join-Path $assetDir 'soundcity-mark.svg'), "<svg xmlns=`"http://www.w3.org/2000/svg`" viewBox=`"80 80 352 352`" role=`"img`" aria-label=`"SoundCity`">$svgDefs$svgMark</svg>", $utf8)

$drawingMark = @"
<GeometryDrawing Geometry="$arc"><GeometryDrawing.Pen><Pen Brush="{StaticResource BrandOrange}" Thickness="34" StartLineCap="Round" EndLineCap="Round"/></GeometryDrawing.Pen></GeometryDrawing>
"@
foreach ($b in $bars) { $drawingMark += "<GeometryDrawing Brush=`"{StaticResource BrandOrange}`"><GeometryDrawing.Geometry><RectangleGeometry Rect=`"$($b -join ',')`" RadiusX=`"15`" RadiusY=`"15`"/></GeometryDrawing.Geometry></GeometryDrawing>" }
$dictionary = @"
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
 <!-- Generated by scripts/Generate-Brand.ps1. -->
 <LinearGradientBrush x:Key="BrandOrange" StartPoint="0,0" EndPoint="0.65,1"><GradientStop Color="#FFC17B" Offset="0"/><GradientStop Color="#FF984C" Offset="0.48"/><GradientStop Color="#FF7133" Offset="1"/></LinearGradientBrush>
 <LinearGradientBrush x:Key="BrandTile" StartPoint="0,0" EndPoint="0.85,1"><GradientStop Color="#222C3B" Offset="0"/><GradientStop Color="#0A0E15" Offset="1"/></LinearGradientBrush>
 <DrawingGroup x:Key="BrandMarkDrawing">$drawingMark</DrawingGroup>
 <DrawingImage x:Key="SoundCityMark"><DrawingImage.Drawing><DrawingGroup><GeometryDrawing Brush="Transparent" Geometry="M 80,80 H 432 V 432 H 80 Z"/><StaticResource ResourceKey="BrandMarkDrawing"/></DrawingGroup></DrawingImage.Drawing></DrawingImage>
 <DrawingImage x:Key="SoundCityIcon"><DrawingImage.Drawing><DrawingGroup>
  <GeometryDrawing Brush="Transparent" Geometry="M 0,0 H 512 V 512 H 0 Z"/>
  <GeometryDrawing Brush="{StaticResource BrandTile}"><GeometryDrawing.Pen><Pen Brush="#354050" Thickness="4"/></GeometryDrawing.Pen><GeometryDrawing.Geometry><RectangleGeometry Rect="8,8,496,496" RadiusX="112" RadiusY="112"/></GeometryDrawing.Geometry></GeometryDrawing>
  <StaticResource ResourceKey="BrandMarkDrawing"/>
 </DrawingGroup></DrawingImage.Drawing></DrawingImage>
</ResourceDictionary>
"@
[IO.File]::WriteAllText((Join-Path $taskRoot 'src\SoundCity.App\Brand.xaml'), $dictionary, $utf8)
$resources = [Windows.Markup.XamlReader]::Parse($dictionary)
$icon = $resources['SoundCityIcon']

function ConvertTo-PngBytes($drawing, [int]$width, [int]$height) {
    $visual = New-Object Windows.Media.DrawingVisual
    $context = $visual.RenderOpen()
    $context.DrawImage($drawing, (New-Object Windows.Rect(0, 0, $width, $height)))
    $context.Close()
    $bitmap = New-Object Windows.Media.Imaging.RenderTargetBitmap($width, $height, 96, 96, ([Windows.Media.PixelFormats]::Pbgra32))
    $bitmap.Render($visual)
    $encoder = New-Object Windows.Media.Imaging.PngBitmapEncoder
    $encoder.Frames.Add([Windows.Media.Imaging.BitmapFrame]::Create($bitmap))
    $stream = New-Object IO.MemoryStream
    $encoder.Save($stream)
    $result = $stream.ToArray()
    $stream.Dispose()
    return ,$result
}
[IO.File]::WriteAllBytes((Join-Path $assetDir 'soundcity-icon.png'), (ConvertTo-PngBytes $icon 1024 1024))
[IO.File]::WriteAllBytes((Join-Path $assetDir 'soundcity-mark.png'), (ConvertTo-PngBytes $resources['SoundCityMark'] 1024 1024))

# PNG-compressed icon frames are supported by Windows 10/11, including high DPI.
$sizes = @(16, 20, 24, 32, 40, 48, 64, 96, 128, 256)
$frames = @($sizes | ForEach-Object { ,(ConvertTo-PngBytes $icon $_ $_) })
$stream = New-Object IO.MemoryStream
$writer = New-Object IO.BinaryWriter($stream)
$writer.Write([uint16]0); $writer.Write([uint16]1); $writer.Write([uint16]$sizes.Count)
$offset = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $size = $sizes[$i] % 256
    $writer.Write([byte]$size); $writer.Write([byte]$size)
    $writer.Write([byte]0); $writer.Write([byte]0)
    $writer.Write([uint16]1); $writer.Write([uint16]32)
    $writer.Write([uint32]$frames[$i].Length); $writer.Write([uint32]$offset)
    $offset += $frames[$i].Length
}
foreach ($frame in $frames) { $writer.Write([byte[]]$frame) }
$writer.Flush()
[IO.File]::WriteAllBytes((Join-Path $appAssetDir 'SoundCity.ico'), $stream.ToArray())
$writer.Dispose(); $stream.Dispose()

# Outlined type gives the SVG lockup the same appearance without requiring fonts.
$word = New-Object Windows.Media.FormattedText('SoundCity', $culture, ([Windows.FlowDirection]::LeftToRight), (New-Object Windows.Media.Typeface('Segoe UI Semibold')), 108, ([Windows.Media.Brushes]::White), 1.0)
$wordGeometry = $word.BuildGeometry((New-Object Windows.Point(350, 66)))
$tag = New-Object Windows.Media.FormattedText('YOUR SOUND. YOUR SPACE.', $culture, ([Windows.FlowDirection]::LeftToRight), (New-Object Windows.Media.Typeface('Segoe UI')), 23, ([Windows.Media.Brushes]::White), 1.0)
$tagGeometry = $tag.BuildGeometry((New-Object Windows.Point(357, 207)))
$wordPath = $wordGeometry.ToString($culture) -replace '^F[01]\s*', ''
$tagPath = $tagGeometry.ToString($culture) -replace '^F[01]\s*', ''
$lockup = New-Object Windows.Media.DrawingGroup
$lockup.Children.Add((New-Object Windows.Media.GeometryDrawing(([Windows.Media.BrushConverter]::new().ConvertFromString('#090B10')), $null, (New-Object Windows.Media.RectangleGeometry((New-Object Windows.Rect(0,0,1200,320)))))))
$scaledIcon = $icon.Drawing.Clone()
$scaledIcon.Transform = New-Object Windows.Media.MatrixTransform(0.5,0,0,0.5,40,32)
$lockup.Children.Add($scaledIcon)
$lockup.Children.Add((New-Object Windows.Media.GeometryDrawing(([Windows.Media.BrushConverter]::new().ConvertFromString('#F3F1EC')), $null, $wordGeometry)))
$lockup.Children.Add((New-Object Windows.Media.GeometryDrawing(([Windows.Media.BrushConverter]::new().ConvertFromString('#A5AFBF')), $null, $tagGeometry)))
$logo = New-Object Windows.Media.DrawingImage($lockup)
[IO.File]::WriteAllBytes((Join-Path $assetDir 'soundcity-logo.png'), (ConvertTo-PngBytes $logo 1800 480))
$logoSvg = "<svg xmlns=`"http://www.w3.org/2000/svg`" viewBox=`"0 0 1200 320`" role=`"img`" aria-label=`"SoundCity - Your sound. Your space.`">$svgDefs<rect width=`"1200`" height=`"320`" fill=`"#090B10`"/><g transform=`"translate(40 32) scale(.5)`">$svgTile$svgMark</g><path fill=`"#F3F1EC`" d=`"$wordPath`"/><path fill=`"#A5AFBF`" d=`"$tagPath`"/></svg>"
[IO.File]::WriteAllText((Join-Path $assetDir 'soundcity-logo.svg'), $logoSvg, $utf8)
Write-Output "Generated SVG, PNG, native WPF drawings and $($sizes.Count) Windows icon sizes."
